/* Уникален списък от градове за избрания куриер (по азбучен ред). */
export function getCitiesForCourier(courier) {
  const offices = COURIER_OFFICES[courier] || [];
  return [...new Set(offices.map((office) => office.city))].sort((a, b) =>
    a.localeCompare(b, "bg")
  );
}

/* Всички офиси на куриера в даден град. */
export function getOfficesForCity(courier, city) {
  return (COURIER_OFFICES[courier] || []).filter((office) => office.city === city);
}
